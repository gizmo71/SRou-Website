<P>
The league is still going strong despite the advent of dozens of new sims. Grand Prix Legends models some of the best cars from the fifties, sixties and early seventies and does it exceptionally well. Despite having been around since 1998, Grand Prix Legends still attracts a loyal following and UKGPL offers the opportunity to race open wheel cars from the original 1967 season and cars from the 1955, 1965, 1966, 1968 and 1969 seasons. The Caterhams, 67 Sports Cars, 66 Can-Ams and 71 Can-Ams provide an additional challenge.</p>

<P>
UKGPL is founded around our 1967 format championship which represents the pinnacle of achievement and this season we will be running two divisions for the 1967 F1 cars. UKGPL will also run championships for the 1965 F1, 1968 F1 and the 1955 Grand Prix cars. Our aim is simply to have some fun racing the 50s and 60s machines.</p>

<P>
We are now an international league having drivers from many countries. A summary of our rules are available in 
<A HREF="//www.simracing.org.uk/smf/index.php?topic=29311.msg562751#msg562751">French</A>, 
<A HREF="//www.simracing.org.uk/smf/index.php?topic=29341.msg562781#msg562781">Portugese</A>, 
<A HREF="//www.simracing.org.uk/smf/index.php?topic=29331.msg562771#msg562771">Italian</A>, 
<A HREF="//www.simracing.org.uk/smf/index.php?topic=29351.msg562791#msg562791">Spanish</A> and 
<A HREF="//www.simracing.org.uk/smf/index.php?topic=29321.msg562761#msg562761">German</A>. Our 1967 F1 championship will again be a joint venture with GPL Brazil. We will be using the token system for the 1967 F1 "Works" and "Privateer" races with the tracks chosen by GPL Brazil.
</P>

<P>
There is something to suit everyone, both newcomers to online racing and those more experienced, so join our forum introduce yourself and enjoy the racing.</P>

<P>
In order to allow drivers to plan their sim racing activities, we have adopted a regular calendar for UKGPL races. We will run two seasons per calendar year. The "Spring" season of ten rounds will start on the second Sunday of the year. The "Autumn" season will start in September and will feature a season of eight rounds can be completed before the end of the calendar year. The "Joe Shaw Memorial" races will be held in the week after the Easter holidays.</p>	

